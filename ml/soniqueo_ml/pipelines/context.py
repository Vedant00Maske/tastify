"""Context experiment stage (Milestone 6): runs `context_experiment` on the research listens and
writes docs/reports/context-benchmark.md (and the raw numbers next to the other reports)."""

import json
import logging
from datetime import UTC, datetime
from typing import Any

from app.core.database import SessionFactory
from app.domains.recommendations.context import SHRINKAGE
from soniqueo_ml.config import get_ml_settings
from soniqueo_ml.evaluation.context_experiment import SHRINKAGE_GRID, run_context_experiment
from soniqueo_ml.evaluation.experiment import load_interactions
from soniqueo_ml.recommendation.catalogue_data import load_catalogue

logger = logging.getLogger(__name__)


def _pct(value: float) -> str:
    return f"{value * 100:+.2f}%"


def render(result: dict[str, Any], generated: str) -> str:
    test, val = result["test"], result["validation"]
    k = int(result["best_shrinkage"])
    lift = result["test_lift"]
    verdict = (
        "Time of day carries signal beyond chance: the daypart model beats the overall one on "
        "unseen days, and clearly more than the shuffled control."
        if lift["daypart"] > max(0.0, lift["shuffled"]) + 0.002
        else "No reliable time-of-day signal: the daypart model does not beat the shuffled "
        "control on unseen days. The context nudge stays off by default."
    )
    rows = "\n".join(
        "| {k:>3} | {d:.4f} | {u:.4f} | {s:.4f} |".format(
            k=k_, d=val[f"daypart@{k_}"], u=val[f"utc@{k_}"], s=val[f"shuffled@{k_}"]
        )
        for k_ in (int(x) for x in SHRINKAGE_GRID)
    )
    local, utc, shuffled = test[f"daypart@{k}"], test[f"utc@{k}"], test[f"shuffled@{k}"]
    session = result["session"]
    sk = session["best_shrinkage"]
    st = session["test"]
    session_lift = session["test_lift"]
    in_session, day_before = st[f"session@{sk:g}"], st[f"previous_day@{sk:g}"]
    session_verdict = (
        "The listens of the last hour predict the next listen's genres clearly better than the "
        "overall profile, and better than the same hour a day earlier: the session is a real "
        "context signal."
        if session_lift["session"] > max(0.0, session_lift["previous_day"]) + 0.002
        else "The last hour of listening does not predict the next listen better than the "
        "control: no session nudge."
    )
    offsets = ", ".join(f"{o:+d} h: {c}" for o, c in sorted(result["offset_distribution"].items()))
    return f"""# Context benchmark: time of day and genre (Milestone 6)

> Generated by `python -m soniqueo_ml context` on {generated}. Method:
> `ml/soniqueo_ml/evaluation/context_experiment.py`. Design: ADR-019. Research data only
> (pseudonymous ListenBrainz listens); nothing here enters the application database.

## Question

Does what a listener plays depend on the time of day enough to use it in ranking? The API's
context nudge assumes it does (`app/domains/recommendations/context.py`).

## Data

- Users: {result["users_total"]:,}; with a clear quiet period (UTC offset inferred):
  {result["users_with_offset"]:,}. Offsets: {offsets}.
- Validation from {result["window"]["validation_start"]}, test from {result["window"]["test_start"]}
  to {result["window"]["end"]} (exclusive); profiles use only earlier listens.
- Test: {test["listens"]:,} listens by {test["users"]:,} users.

## Results (cross-entropy of a listen's genres; lower is better)

Shrinkage chosen on validation: **K = {k}** (serving default: {int(SHRINKAGE)}).

| Model (test period) | Cross-entropy | Change vs overall |
| --- | --- | --- |
| Overall genre profile | {test["overall"]:.4f} | |
| Daypart profile, local time (inferred offset) | {local:.4f} | {_pct(lift["daypart"])} |
| Daypart profile, UTC hours | {utc:.4f} | {_pct(lift["utc"])} |
| Daypart, shuffled within user (control) | {shuffled:.4f} | {_pct(lift["shuffled"])} |

Validation, by shrinkage (overall: {val["overall"]:.4f}):

| K | Daypart (local) | UTC | Shuffled |
| --- | --- | --- | --- |
{rows}

At test time, {result["daypart_evidence_share"] * 100:.0f}% of user-dayparts have at least
{result["min_daypart_events"]} listens, the minimum the API requires before it uses a daypart.

## Session context (the previous hour)

Time-zone free: windows are relative to each listen. Compared on listens that have both a
session (at least one listen in the previous hour) and a control window (the same hour one day
earlier). Shrinkage chosen on validation: **K = {sk:g}**.

| Model (test period) | Cross-entropy | Change vs overall |
| --- | --- | --- |
| Overall genre profile | {st["overall"]:.4f} | |
| Previous hour (session) | {in_session:.4f} | {_pct(session_lift["session"])} |
| Same hour, previous day (control) | {day_before:.4f} | {_pct(session_lift["previous_day"])} |

Test: {st["listens"]:,} listens by {st["users"]:,} users. Repeated plays of the same track
within the hour count as session evidence, as they do in the API.

## Conclusion

Time of day: {verdict}

Session: {session_verdict}

Caveats: offsets are inferred from activity, not known; the period covers two weeks, so weekly
patterns are not measured; genre cross-entropy shows whether a signal exists, not how much it
improves recommendations, which the online experiment (`context-ranking`) measures.
"""


async def stage_context() -> dict[str, Any]:
    settings = get_ml_settings()
    interactions = load_interactions(settings.processed_dir / "interactions.parquet")
    async with SessionFactory() as session:
        catalogue = await load_catalogue(session)
    logger.info("context experiment: %d listens", len(interactions))
    result = run_context_experiment(interactions, catalogue)
    generated = datetime.now(UTC).strftime("%Y-%m-%d")
    raw = settings.data_dir / "reports" / "context-benchmark.json"
    raw.parent.mkdir(parents=True, exist_ok=True)
    raw.write_text(json.dumps(result, indent=2), encoding="utf-8")
    report = settings.reports_dir / "context-benchmark.md"
    report.write_text(render(result, generated), encoding="utf-8")
    logger.info("context experiment written to %s", report)
    return result
